function format(template: string, params?: Record<string, string | number>): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const value = params[key];
    return value === undefined ? match : String(value);
  });
}

function getVscodeApi(): typeof import('vscode') | undefined {
  try {
    return require('vscode') as typeof import('vscode');
  } catch {
    return undefined;
  }
}

export function normalizeCodeGroupLanguage(value?: string): CodeGroupLanguage {
  switch (value) {
    case 'fr':
    case 'de':
    case 'hu':
    case 'es':
    case 'it':
    case 'pt-BR':
    case 'ja':
    case 'zh-CN':
    case 'en':
      return value;
    default:
      return DEFAULT_LANGUAGE;
  }
}

export function getConfiguredLanguage(): CodeGroupLanguage {
  const vscodeApi = getVscodeApi();
  if (!vscodeApi) {
    return DEFAULT_LANGUAGE;
  }

  const configuredLanguage = vscodeApi.workspace
    .getConfiguration('codegroup')
    .get<string>('language', DEFAULT_LANGUAGE);

  return normalizeCodeGroupLanguage(configuredLanguage);
}

export function translateForLanguage(
  language: CodeGroupLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const template = TRANSLATIONS[language][key] ?? EN_TRANSLATIONS[key];
  return format(template, params);
}

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  return translateForLanguage(getConfiguredLanguage(), key, params);
}

